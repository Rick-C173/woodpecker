# -*- coding: utf-8 -*-
"""Apifox cloud sync, cross-platform (works under cmd.exe and sh).

Usage:
  python scripts/apifox_sync.py ignore      # add-only sync
  python scripts/apifox_sync.py overwrite   # full overwrite sync
  python scripts/apifox_sync.py backup      # full project snapshot only

Steps (ignore/overwrite):
  1. backup current cloud project to bin/apifox-backup/
  2. import docs/swagger.json with the requested conflict mode
  3. SSE endpoints (Ask/Regenerate): 4xx contentType back to json
     (OpenAPI 2.0 global produces text/event-stream mislabels them)

Requires: apifox CLI logged in; docs/swagger.json generated by `make api-docs`.
"""
import json, os, subprocess, sys, time

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.environ.get("APIFOX_PROJECT", "9076931")
SPEC = os.path.join(REPO, "docs", "swagger.json")
BACKUP_DIR = os.path.join(REPO, "bin", "apifox-backup")
SSE_ENDPOINT_IDS = (541107872, 541107899)  # Ask / Regenerate
TMP = os.path.join(os.environ.get("TEMP", "/tmp"), "apifox_sync")


def sh(args):
    r = subprocess.run(args, capture_output=True)
    out = r.stdout.decode("utf-8", "replace")
    err = r.stderr.decode("utf-8", "replace")
    return r.returncode, out, err


def backup(tag):
    os.makedirs(BACKUP_DIR, exist_ok=True)
    out = os.path.join(BACKUP_DIR, "%s.apifox.json" % tag)
    rc, o, e = sh(["apifox", "export", "--project", PROJECT, "--format", "apifox", "--output", out])
    if rc != 0:
        print("backup FAILED:", e[:200] or o[:200])
        return False
    print("backup -> %s" % out)
    return True


def sync(mode):
    if not os.path.exists(SPEC):
        print("missing %s — run `make api-docs` first" % SPEC)
        sys.exit(1)
    if not backup("before-%s" % mode):
        sys.exit(1)
    rc, o, e = sh(["apifox", "import", "--project", PROJECT, "--format", "openapi",
                   "--file", SPEC, "--overwrite-mode", mode])
    try:
        d = json.loads(o)
        api = (d.get("data") or {}).get("apiCollection", {}).get("item", {})
        print("sync[%s]: create=%s update=%s ignore=%s error=%s"
              % (mode, api.get("createCount"), api.get("updateCount"),
                 api.get("ignoreCount"), api.get("errorCount")))
    except Exception:
        print("sync parse error:", (o or e)[:300])
        sys.exit(1)
    fix_sse_4xx()


def fix_sse_4xx():
    os.makedirs(TMP, exist_ok=True)
    for eid in SSE_ENDPOINT_IDS:
        rc, o, _ = sh(["apifox", "endpoint", "get", str(eid), "--project", PROJECT])
        try:
            data = json.loads(o)["data"]
        except Exception:
            print("sse %s: get failed" % eid)
            continue
        changed = 0
        for r in data.get("responses") or []:
            if str(r.get("code")).startswith("4") and r.get("contentType") == "eventStream":
                r["contentType"] = "json"
                r["mediaType"] = "application/json"
                changed += 1
        if not changed:
            print("sse %s: 4xx contentType ok" % eid)
            continue
        tf = os.path.join(TMP, "sse_%s.json" % eid)
        with open(tf, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False)
        rc, o, _ = sh(["apifox", "endpoint", "update", str(eid), "--project", PROJECT, "--file", tf])
        ok = json.loads(o).get("success")
        print("sse %s: fixed %d 4xx -> json (update=%s)" % (eid, changed, ok))


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("ignore", "overwrite", "backup"):
        print(__doc__)
        sys.exit(1)
    mode = sys.argv[1]
    if mode == "backup":
        ok = backup("snapshot-" + time.strftime("%Y%m%d-%H%M%S"))
        sys.exit(0 if ok else 1)
    sync(mode)


if __name__ == "__main__":
    main()
